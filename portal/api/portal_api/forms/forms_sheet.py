"""The application forms' review sheet: every section and field of every form, with
what applicants read, when each question is asked (in words), the Code text it rests
on, and its approval. Generated by `python -m portal_api.forms forms-sheet`."""

from portal_api.forms.formdefs import FormDef
from portal_api.ruleset import Ruleset

SOURCES = {
    "question": "asked in the wizard",
    "property": "from the property lookup (staff confirm)",
    "account": "from the applicant's sign-in",
    "derived": "copied from another field",
    "at_submit": "filled when the applicant signs and submits (M6)",
    "staff": "staff fill this in",
}

DECISIONS = [
    "**Fields come from the Town's current Planning Application packet** (Cover Sheet, Use Form, Building "
    "Form, Components Section), read from the scanned 2025 applications in `docs/`. The Entrance / Driveway "
    "Form is new, drafted from Art. 3 §§7–8 and §12.",
    "**Buildings and components repeat**: the form prints one Building Form per building and one "
    "Components Section per addition, porch, deck or other component.",
    "**Signatures, dates and \"Name (print)\"** are filled when the applicant signs and submits (Milestone 6).",
]

QUESTIONS = [
    ("Is a site plan or sketch required for a Small Project Plan?",
     "Drafted as optional, with \"staff may ask for one\". The packet's Shoreland form requires a scaled site plan; "
     "the Small Project Plan pages seen do not say."),
    ("\"Standard Met?\" column dropped",
     "The paper Building Form has \"District Standard / Standard Met?\" columns. \"Standard Met?\" is a verdict, "
     "which the portal never gives (spec §5). The District Standard column becomes Milestone 6's flags."),
    ("Special Use Building added",
     "The building types follow Art. 5 §1.c, which lists Special Use Building; the paper form omits it."),
    ("Name added to the Applicant, Owner and Agent blocks",
     "The paper takes the applicant's name only at the signature and the owner's and agent's not at all."),
    ("Is anything missing from the blank packet?",
     "The fields were read from filled-in scans. If the Town's blank packet has more pages (a second Building "
     "Form page, the \"Other Structures Form\"), they are not here yet."),
]


def _cite(ref: str) -> str:
    art, *rest = ref.split(".")
    return f"Art. {art} §{'.'.join(rest)}"


def _field_named(form: FormDef, fid: str):
    try:
        return form.field(fid)[1]
    except KeyError:
        return None


def _value(form: FormDef, fid: str | None, v) -> str:
    f = _field_named(form, fid) if fid else None
    if isinstance(v, bool):
        return "Yes" if v else "No"
    if f is not None and f.options:
        return next((o.official for o in f.options if o.value == v), str(v))
    return str(v)


def _subject(form: FormDef, path: str) -> tuple[str, str | None]:
    scope, _, name = path.partition(".")
    if scope == "property":
        return {"on_state_highway": "the lot is on a State road"}.get(name, f"the property's {name}"), None
    f = _field_named(form, name)
    label = f"“{f.official_label}”" if f else f"`{name}`"
    if scope == "item":
        kind = next((s.repeat.kind for s in form.sections if s.repeat and any(x.id == name for x in s.fields)), "item")
        label += f" (this {kind})"
    return label, name


def condition_words(form: FormDef, cond) -> str:
    """A condition as a sentence fragment; anything unusual prints as the raw condition."""
    try:
        (op, arg), = cond.items()
        if op in ("all", "any"):
            return (" and " if op == "all" else " or ").join(f"({condition_words(form, c)})" for c in arg)
        if op == "not":
            return f"not ({condition_words(form, arg)})"
        if op == "known":
            return f"{_subject(form, arg)[0]} has an answer"
        path, v = arg
        if path == "property.on_state_highway" and op == "ne" and v is False:
            return "the lot is not known to be off State roads (on a State road, or unknown)"
        subject, fid = _subject(form, path)
        if op == "eq":
            return f"{subject} is {_value(form, fid, v)}"
        if op == "ne":
            return f"{subject} is not {_value(form, fid, v)}"
        if op == "oneof":
            return f"{subject} is " + " or ".join(_value(form, fid, x) for x in v)
        if op == "has":
            return f"{subject} includes {_value(form, fid, v)}"
        words = {"gt": "more than {}", "gte": "{} or more", "lt": "less than {}", "lte": "{} or less"}
        n = int(v) if float(v).is_integer() else v
        return f"{subject} is {words[op].format(n)}"
    except (AttributeError, KeyError, TypeError, ValueError):
        return f"`{cond}`"


def _status(e) -> str:
    if e.status == "approved":
        return f"- Approved by {e.approved_by}, on {e.approved_on}."
    return "- **Draft — awaiting the chair's approval.**"


def _section(ruleset: Ruleset, form: FormDef, s) -> list[str]:
    out = [f"### {s.official_title} (`{s.id}`)", "",
           f"- Wizard chapter: {s.chapter}",
           *([f"- Repeats: one per {s.repeat.kind} ({s.repeat.min} to {s.repeat.max}); "
              f"the wizard offers “{s.repeat.add_label}”"] if s.repeat else []),
           *([f"- Printed and asked only when {condition_words(form, s.show_if)}"] if s.show_if else []),
           _status(s), ""]
    for f in s.fields:
        out += [f"#### {f.official_label} (`{f.id}`)", "", f"- Source: {SOURCES[f.source]}"
                + (f" — `{f.from_}`" if f.from_ else "") + (" (the applicant may correct it)" if f.may_correct else "")]
        if f.is_question:
            out.append(f"- Applicants read: “{f.label}”")
            if f.help:
                out.append(f"- Help: {f.help}")
            kind = f.type + (f" ({f.unit})" if f.unit else "")
            if f.min is not None or f.max is not None:
                kind += f", {f.min if f.min is not None else ''}–{f.max if f.max is not None else ''}"
            out.append(f"- Answer: {kind}" + ("; required" if f.required else "; optional")
                       + ("; “I don't know yet” allowed" if f.allow_unknown else ""))
            for o in f.options:
                out.append(f"  - {o.official} — applicants read “{o.label}”")
        if f.show_if:
            out.append(f"- Asked only when {condition_words(form, f.show_if)}")
        out.append(_status(f))
        if f.why:
            out += [f"- Rests on {_cite(f.why)}:", "", *[f"  > {line}" for line in ruleset.cite(f.why).splitlines()]]
        out.append("")
    return out


def forms_sheet(ruleset: Ruleset, forms: list[FormDef]) -> str:
    drafts = sum((s.status == "draft") + sum(f.status == "draft" for f in s.fields)
                 for form in forms for s in form.sections
                 if not (form is not forms[0] and s.file == "cover-sheet.v1.yaml"))
    out = [f"# Application forms: approval record ({ruleset.key})", "",
           "Every section and field of the three application forms, with what applicants read, when each "
           "question is asked, the Code text it rests on, and its approval. Production refuses a form while "
           "any of its entries is a draft.", "",
           (f"**{drafts} entries await approval.**" if drafts else "**Every entry is approved.**"), "",
           "To approve an entry, change `status: draft` to `status: approved` with `approved_by` and "
           "`approved_on` in its YAML file (`portal/api/portal_api/forms/definitions/forms/`).", "",
           "## Decisions so far", "", *[f"- {d}" for d in DECISIONS], "",
           "## Questions for the chair", "", *[f"{i}. **{q}{'' if q.endswith('?') else '.'}** {why}" for i, (q, why) in enumerate(QUESTIONS, 1)], ""]
    cover_done = False
    for form in forms:
        cover = [s for s in form.sections if s.file == "cover-sheet.v1.yaml"]
        if cover and not cover_done:
            out += ["## Cover Sheet (part of every application)", ""]
            for s in cover:
                out += _section(ruleset, form, s)
            cover_done = True
        out += [f"## {form.official_title}", "", f"`{form.key}` version {form.version}; the Cover Sheet comes first.", ""]
        for s in form.sections:
            if s.file != "cover-sheet.v1.yaml":
                out += _section(ruleset, form, s)
    return "\n".join(out)
